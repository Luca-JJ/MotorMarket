package motormarket.data;

import java.sql.Connection;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * Represents a Review posted by a user within the marketplace.
 * This class maps directly to the recensioni table and handles mutually 
 * exclusive feedback targeting either a specific spare part or a vehicle model.
 */
public class Review {

    /**
     * Defines whether the review targets a vehicle model or a spare part.
     */
    public enum ReviewType {
        /** The review evaluates a spare part. */
        PEZZO("Pezzo"),
        /** The review evaluates a specific vehicle model. */
        MODELLO("Modello");

        /** The literal string representation stored within the database column. */
        private final String dbValue;

        ReviewType(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the review type.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a raw input string into its corresponding ReviewType enum constant.
         * @param text The string name of the review type to convert.
         * @return The matching {@link ReviewType} enum constant.
         * @throws IllegalArgumentException If the provided text does not match any review type.
         */
        public static ReviewType fromString(String text) {
            for (ReviewType type : ReviewType.values()) {
                if (type.getDbValue().equalsIgnoreCase(text) || type.name().equalsIgnoreCase(text)) {
                    return type;
                }
            }
            throw new IllegalArgumentException("Invalid review type: " + text);
        }
    }

    private int reviewId;
    private int rating;
    private String title;
    private LocalDate reviewDate;
    private String text;
    private ReviewType reviewType;
    private User user;
    private SparePart sparePart; // Nullable if the review is for a CarModel
    private CarModel carModel;   // Nullable if the review is for a SparePart

    /**
     * 3. Complete Object-Oriented Constructor.
     * @param reviewId   The unique system identifier generated by the database (IdRecensione).
     * @param rating     The numerical score statement given (Voto).
     * @param title      The brief summary text of the review (Titolo).
     * @param reviewDate The timestamp when the review was written (DataRecensione).
     * @param text       The full body text of the feedback statement (Testo).
     * @param reviewType The selection parameter discriminator (TipoRecensione).
     * @param user       The authoring {@link User} account instance (IdUtente).
     * @param sparePart  The associated {@link SparePart} instance, or {@code null} if this is a model review.
     * @param carModel   The associated {@link CarModel} instance, or {@code null} if this is a part review.
     */
    public Review(int reviewId, int rating, String title, LocalDate reviewDate, String text, 
                  ReviewType reviewType, User user, SparePart sparePart, CarModel carModel) {
        this.reviewId = reviewId;
        this.rating = rating;
        this.title = title;
        this.reviewDate = reviewDate;
        this.text = text;
        this.reviewType = reviewType;
        this.user = user;
        this.sparePart = sparePart;
        this.carModel = carModel;
    }

    public int getReviewId() {
        return reviewId;
    }

    public int getRating() {
        return rating;
    }

    public String getTitle() {
        return title;
    }

    public LocalDate getReviewDate() {
        return reviewDate;
    }

    public String getText() {
        return text;
    }

    public ReviewType getReviewType() {
        return reviewType;
    }

    public User getUser() {
        return user;
    }

    public SparePart getSparePart() {
        return sparePart;
    }

    public CarModel getCarModel() {
        return carModel;
    }

    @Override
    public String toString() {
        return "Review{" +
                "reviewId=" + reviewId +
                ", rating=" + rating +
                ", title='" + title + '\'' +
                ", reviewDate=" + reviewDate +
                ", text='" + text + '\'' +
                ", reviewType=" + reviewType +
                ", user=" + (user != null ? user.getUserId() : "null") +
                ", sparePart=" + (sparePart != null ? sparePart.getPartId() : "null") +
                ", carModel=" + (carModel != null ? carModel.getModelId() : "null") +
                '}';
    }

    /**
     * Data Access Object (DAO) providing persistent storage capabilities for {@link Review} entities.
     */
    public static final class DAO {

        /**
         * Inserts a car model review using a single optimized SQL query.
         * It verifies if the user has purchased a car of this specific model before inserting.
         * @param connection the active database connection
         * @param userId the ID of the user writing the review
         * @param modelId the ID of the car model being reviewed
         * @param rating the score given (1-5)
         * @param title the title
         * @param text the review text
         * @return true if the review was inserted, false if the user never purchased this model
         * @throws DAOException if any database access error occurs
         */
        public static boolean addModelReview(Connection connection, int userId, int modelId, int rating, String title, String text) throws DAOException {
            try (var statement = DAOUtils.prepare(connection, Queries.INSERT_MODEL_REVIEW, userId, modelId, rating, title, text, userId, modelId)) {
                
                int rowsInserted = statement.executeUpdate();
                return rowsInserted > 0;
                
            } catch (Exception e) {
                throw new DAOException(e);
            }
        }

        /**
         * Inserts a spare part review using a single optimized SQL query.
         * It verifies if the user has purchased this specific spare part before inserting.
         * @param connection the active database connection
         * @param userId the ID of the user writing the review
         * @param partId the ID of the spare part being reviewed
         * @param rating the score given (1-5)
         * @param title the title
         * @param text the review text
         * @return true if the review was inserted, false if the user never purchased this spare part
         * @throws DAOException if any database access error occurs
         */
        public static boolean addSparePartReview(Connection connection, int userId, int partId, int rating, String title, String text) throws DAOException {
            try (var statement = DAOUtils.prepare(connection, Queries.INSERT_SPARE_PART_REVIEW, userId, partId, rating, title, text, userId, partId)) {
                
                int rowsInserted = statement.executeUpdate();
                return rowsInserted > 0;
                
            } catch (Exception e) {
                throw new DAOException(e);
            }
        }

        /**
         * Fetches the average rating and all individual reviews (with author username) for a car model.
         * @param connection the active database connection
         * @param modelId the ID of the car model
         * @return a list of ReviewDetail objects
         * @throws DAOException if any database access error occurs
         */
        public static List<ReviewDetail> getModelReviews(Connection connection, int modelId) {
            List<ReviewDetail> reviews = new ArrayList<>();
            
            try (var statement = DAOUtils.prepare(connection, Queries.GET_MODEL_REVIEWS, modelId);
                var resultSet = statement.executeQuery()) {
                
                while (resultSet.next()) {
                    ReviewDetail review = new ReviewDetail(
                        resultSet.getString("Titolo"),
                        resultSet.getString("Testo"),
                        resultSet.getInt("Voto"),
                        resultSet.getDate("DataRecensione").toLocalDate(),
                        resultSet.getString("Nome"),
                        resultSet.getString("Cognome"),
                        resultSet.getDouble("MediaVoti")
                    );
                    reviews.add(review);
                }
                
            } catch (Exception e) {
                throw new DAOException(e);
            }
            return reviews;
        }

        /**
         * Fetches the average rating and all individual reviews (with author username) for a spare part.
         * @param connection the active database connection
         * @param partId the ID of the spare part
         * @return a list of ReviewDetail objects
         * @throws DAOException if any database access error occurs
         */
        public static List<ReviewDetail> getSparePartReviews(Connection connection, int partId) {
            List<ReviewDetail> reviews = new ArrayList<>();
            
            try (var statement = DAOUtils.prepare(connection, Queries.GET_SPARE_PART_REVIEWS, partId);
                var resultSet = statement.executeQuery()) {
                
                while (resultSet.next()) {
                    ReviewDetail review = new ReviewDetail(
                        resultSet.getString("Titolo"),
                        resultSet.getString("Testo"),
                        resultSet.getInt("Voto"),
                        resultSet.getDate("DataRecensione").toLocalDate(),
                        resultSet.getString("Nome"),
                        resultSet.getString("Cognome"),
                        resultSet.getDouble("MediaVoti")
                    );
                    reviews.add(review);
                }
                
            } catch (Exception e) {
                throw new DAOException(e);
            }
            return reviews;
        }
    }

}

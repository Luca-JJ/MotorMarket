package motormarket.data;

import java.time.LocalDate;

/**
 * Represents a Review posted by a user within the marketplace.
 * This class maps directly to the recensioni table and handles mutually 
 * exclusive feedback targeting either a specific spare part or a vehicle model.
 */
public class Review {

    /**
     * Defines whether the review targets a vehicle model or a spare part.
     */
    public enum ReviewType {
        /** The review evaluates a spare part. */
        PEZZO("Pezzo"),
        /** The review evaluates a specific vehicle model. */
        MODELLO("Modello");

        /** The literal string representation stored within the database column. */
        private final String dbValue;

        ReviewType(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the review type.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a raw input string into its corresponding ReviewType enum constant.
         * @param text The string name of the review type to convert.
         * @return The matching {@link ReviewType} enum constant.
         * @throws IllegalArgumentException If the provided text does not match any review type.
         */
        public static ReviewType fromString(String text) {
            for (ReviewType type : ReviewType.values()) {
                if (type.getDbValue().equalsIgnoreCase(text) || type.name().equalsIgnoreCase(text)) {
                    return type;
                }
            }
            throw new IllegalArgumentException("Invalid review type: " + text);
        }
    }

    private int reviewId;
    private int rating;
    private String title;
    private LocalDate reviewDate;
    private String text;
    private ReviewType reviewType;
    private User user;
    private SparePart sparePart; // Nullable if the review is for a CarModel
    private CarModel carModel;   // Nullable if the review is for a SparePart

    /**
     * 3. Complete Object-Oriented Constructor.
     * @param reviewId   The unique system identifier generated by the database (IdRecensione).
     * @param rating     The numerical score statement given (Voto).
     * @param title      The brief summary text of the review (Titolo).
     * @param reviewDate The timestamp when the review was written (DataRecensione).
     * @param text       The full body text of the feedback statement (Testo).
     * @param reviewType The selection parameter discriminator (TipoRecensione).
     * @param user       The authoring {@link User} account instance (IdUtente).
     * @param sparePart  The associated {@link SparePart} instance, or {@code null} if this is a model review.
     * @param carModel   The associated {@link CarModel} instance, or {@code null} if this is a part review.
     */
    public Review(int reviewId, int rating, String title, LocalDate reviewDate, String text, 
                  ReviewType reviewType, User user, SparePart sparePart, CarModel carModel) {
        this.reviewId = reviewId;
        this.rating = rating;
        this.title = title;
        this.reviewDate = reviewDate;
        this.text = text;
        this.reviewType = reviewType;
        this.user = user;
        this.sparePart = sparePart;
        this.carModel = carModel;
    }

    public int getReviewId() {
        return reviewId;
    }

    public int getRating() {
        return rating;
    }

    public String getTitle() {
        return title;
    }

    public LocalDate getReviewDate() {
        return reviewDate;
    }

    public String getText() {
        return text;
    }

    public ReviewType getReviewType() {
        return reviewType;
    }

    public User getUser() {
        return user;
    }

    public SparePart getSparePart() {
        return sparePart;
    }

    public CarModel getCarModel() {
        return carModel;
    }

    @Override
    public String toString() {
        return "Review{" +
                "reviewId=" + reviewId +
                ", rating=" + rating +
                ", title='" + title + '\'' +
                ", reviewDate=" + reviewDate +
                ", text='" + text + '\'' +
                ", reviewType=" + reviewType +
                ", user=" + (user != null ? user.getUserId() : "null") +
                ", sparePart=" + (sparePart != null ? sparePart.getPartId() : "null") +
                ", carModel=" + (carModel != null ? carModel.getModelId() : "null") +
                '}';
    }

    /**
     * Data Access Object (DAO) providing persistent storage capabilities for {@link Review} entities.
     */
    public static final class DAO {

    }

}

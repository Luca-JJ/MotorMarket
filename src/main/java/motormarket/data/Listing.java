package motormarket.data;

import java.math.BigDecimal;
import java.time.LocalDate;

/**
 * Represents a marketplace Listing (advertisement) posted by a user.
 * This class maps directly to the annunci table and supports exclusive 
 * categorization for either car or a spare part.
 */
public class Listing {

    /**
     * Defines the operational lifecycles of a listing within the marketplace.
     */
    public enum ListingStatus {
        /** The listing is public and items are available for purchase. */
        ATTIVO("Attivo"),
        /** The listing has been hidden or deactivated by the creator or admin. */
        DISATTIVATO("Disattivato"),
        /** The listed item has been sold successfully. */
        VENDUTO("Venduto");

        private final String dbValue;

        ListingStatus(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the listing status.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a string text into its matching ListingStatus enum constant.
         * @param text The string status identifier.
         * @return The corresponding {@link ListingStatus} constant.
         * @throws IllegalArgumentException If the text does not match a valid status.
         */
        public static ListingStatus fromString(String text) {
            for (ListingStatus status : ListingStatus.values()) {
                if (status.getDbValue().equalsIgnoreCase(text) || status.name().equalsIgnoreCase(text)) {
                    return status;
                }
            }
            throw new IllegalArgumentException("Invalid listing status: " + text);
        }
    }

    /**
     * Defines whether the listing advertises a car or a spare part.
     */
    public enum ListingType {
        /** The listing is selling a car. */
        AUTO("Auto"),
        /** The listing is selling a spare part. */
        PEZZO("Pezzo");

        private final String dbValue;

        ListingType(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the listing type.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a string text into its matching ListingType enum constant.
         * @param text The string type identifier.
         * @return The corresponding {@link ListingType} constant.
         * @throws IllegalArgumentException If the text does not match a valid type.
         */
        public static ListingType fromString(String text) {
            for (ListingType type : ListingType.values()) {
                if (type.getDbValue().equalsIgnoreCase(text) || type.name().equalsIgnoreCase(text)) {
                    return type;
                }
            }
            throw new IllegalArgumentException("Invalid listing type: " + text);
        }
    }

    private int listingId;
    private LocalDate creationDate;
    private ListingStatus status;
    private BigDecimal price;
    private ListingType listingType;
    private Car car;             // Nullable if listing is for a SparePart
    private SparePart sparePart; // Nullable if listing is for a Car
    private User user;


    /**
     * Complete Object-Oriented Constructor.
     * @param listingId    The unique system identifier generated by the database (idAnnuncio).
     * @param creationDate The date the listing was published (DataInserimento).
     * @param status       The operational state of the listing (Stato).
     * @param price        The monetary valuation set for the item (Prezzo).
     * @param listingType  The classification parameter selector (TipoAnnuncio).
     * @param car          The associated {@link Car} instance, or {@code null} if this is a part listing.
     * @param sparePart    The associated {@link SparePart} instance, or {@code null} if this is a car listing.
     * @param user         The seller {@link User} account instance (IdUtente).
     */
    public Listing(int listingId, LocalDate creationDate, ListingStatus status, BigDecimal price, 
                   ListingType listingType, Car car, SparePart sparePart, User user) {
        this.listingId = listingId;
        this.creationDate = creationDate;
        this.status = status;
        this.price = price;
        this.listingType = listingType;
        this.car = car;
        this.sparePart = sparePart;
        this.user = user;
    }


    public int getListingId() {
        return listingId;
    }


    public LocalDate getCreationDate() {
        return creationDate;
    }


    public ListingStatus getStatus() {
        return status;
    }


    public BigDecimal getPrice() {
        return price;
    }


    public ListingType getListingType() {
        return listingType;
    }


    public Car getCar() {
        return car;
    }


    public SparePart getSparePart() {
        return sparePart;
    }


    public User getUser() {
        return user;
    }
    
    @Override
    public String toString() {
        return "Listing{" +
                "listingId=" + listingId +
                ", creationDate=" + creationDate +
                ", status=" + status +
                ", price=" + price +
                ", listingType=" + listingType +
                ", car=" + (car != null ? car.getCarId() : "null") +
                ", sparePart=" + (sparePart != null ? sparePart.getPartId() : "null") +
                ", user=" + (user != null ? user.getUserId() : "null") +
                '}';
    }

    /**
     * Data Access Object (DAO) providing persistent storage capabilities for {@link Listing} entities.
     */
    public static final class DAO {

    }
}

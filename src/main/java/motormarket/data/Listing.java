package motormarket.data;

import java.math.BigDecimal;
import java.time.LocalDate;

/**
 * Represents a marketplace Listing (advertisement) posted by a user.
 * This class maps directly to the annunci table and supports exclusive 
 * categorization for either car or a spare part.
 * * @author YourName
 * @version 1.0
 */
public class Listing {

    /**
     * Defines the operational lifecycles of a listing within the marketplace.
     */
    public enum ListingStatus {
        /** The listing is public and items are available for purchase. */
        ATTIVO("Attivo"),
        /** The listing has been hidden or deactivated by the creator or admin. */
        DISATTIVATO("Disattivato"),
        /** The listed item has been sold successfully. */
        VENDUTO("Venduto");

        private final String dbValue;

        ListingStatus(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the listing status.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a string text into its matching ListingStatus enum constant.
         * @param text The string status identifier.
         * @return The corresponding {@link ListingStatus} constant.
         * @throws IllegalArgumentException If the text does not match a valid status.
         */
        public static ListingStatus fromString(String text) {
            for (ListingStatus status : ListingStatus.values()) {
                if (status.getDbValue().equalsIgnoreCase(text) || status.name().equalsIgnoreCase(text)) {
                    return status;
                }
            }
            throw new IllegalArgumentException("Invalid listing status: " + text);
        }
    }

    /**
     * Defines whether the listing advertises a car or a spare part.
     */
    public enum ListingType {
        /** The listing is selling a car. */
        AUTO("Auto"),
        /** The listing is selling a spare part. */
        PEZZO("Pezzo");

        private final String dbValue;

        ListingType(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the listing type.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a string text into its matching ListingType enum constant.
         * * @param text The string type identifier.
         * @return The corresponding {@link ListingType} constant.
         * @throws IllegalArgumentException If the text does not match a valid type.
         */
        public static ListingType fromString(String text) {
            for (ListingType type : ListingType.values()) {
                if (type.getDbValue().equalsIgnoreCase(text) || type.name().equalsIgnoreCase(text)) {
                    return type;
                }
            }
            throw new IllegalArgumentException("Invalid listing type: " + text);
        }
    }

    private int listingId;
    private Integer carId;       // Can be null if the listing is for a spare part
    private Integer partId;      // Can be null if the listing is for a car
    private LocalDate postDate;
    private ListingStatus status;
    private BigDecimal price;
    private ListingType type;
    private int userId;

    /**
     * SPECIFIC CONSTRUCTOR FOR CARS (Handles Part ID as Null)
     * <p>
     * Use this constructor to instantiate a new Car listing.
     * </p>
     * @param listingId The unique system identifier generated by the database.
     * @param carId    The unique database ID of the vehicle.
     * @param postDate The publishing date.
     * @param status   The initial lifecycle status of the listing.
     * @param price    The decimal selling price.
     * @param userId   The ID of the user creating the listing.
     */
    public Listing(int listingId, Integer carId, LocalDate postDate, ListingStatus status, BigDecimal price, int userId) {
        this.listingId = listingId;
        this.carId = carId;
        this.partId = null;
        this.postDate = postDate;
        this.status = status;
        this.price = price;
        this.type = ListingType.AUTO;
        this.userId = userId;
    }

    /**
     * SPECIFIC CONSTRUCTOR FOR SPARE PARTS (Handles Car ID as Null)
     * <p>
     * Use this constructor to instantiate a new Spare Part listing.
     * </p>
     * @param listingId The unique system identifier generated by the database.
     * @param postDate The publishing date.
     * @param status   The initial lifecycle status of the listing.
     * @param price    The decimal selling price.
     * @param partId   The unique database ID of the spare part.
     * @param userId   The ID of the user creating the listing.
     */
    public Listing(int listingId, LocalDate postDate, ListingStatus status, BigDecimal price, Integer partId, int userId) {
        this.listingId = listingId;
        this.carId = null;
        this.partId = partId;
        this.postDate = postDate;
        this.status = status;
        this.price = price;
        this.type = ListingType.PEZZO;
        this.userId = userId;
    }

    /**
     * COMPLETE CONSTRUCTOR (With ID and explicit types)
     * <p>
     * Primarily used by the DAO layer to rebuild a Listing object from full database records.
     * </p>
     * @param listingId The unique system identifier generated by the database.
     * @param carId     The ID of the car (can be {@code null}).
     * @param partId    The ID of the spare part (can be {@code null}).
     * @param postDate  The date the listing was recorded.
     * @param status    The current status of the advertisement.
     * @param price     The numeric price.
     * @param type      The classification type (AUTO or PEZZO).
     * @param userId    The creator's unique ID.
     */
    public Listing(int listingId, Integer carId, Integer partId, LocalDate postDate, ListingStatus status, BigDecimal price, ListingType type, int userId) {
        this.listingId = listingId;
        this.carId = carId;
        this.partId = partId;
        this.postDate = postDate;
        this.status = status;
        this.price = price;
        this.type = type;
        this.userId = userId;
    }

    public int getListingId() {
        return listingId;
    }

    public Integer getCarId() {
        return carId;
    }

    public Integer getPartId() {
        return partId;
    }

    public LocalDate getPostDate() {
        return postDate;
    }

    public ListingStatus getStatus() {
        return status;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public ListingType getType() {
        return type;
    }

    public int getUserId() {
        return userId;
    }
    
    @Override
    public String toString() {
        return "Listing{" +
                "listingId=" + listingId +
                ", carId=" + carId +
                ", partId=" + partId +
                ", postDate=" + postDate +
                ", status=" + status +
                ", price=" + price +
                ", type=" + type +
                ", userId=" + userId +
                '}';
    }

    /**
     * Data Access Object (DAO) providing persistent storage capabilities for {@link Listing} entities.
     */
    public static final class DAO {

    }
}

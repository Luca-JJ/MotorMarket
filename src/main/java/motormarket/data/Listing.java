package motormarket.data;

import java.math.BigDecimal;
import java.sql.Connection;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

import motormarket.data.Car.Availability;
import motormarket.data.Car.TransmissionType;

/**
 * Represents a marketplace Listing (advertisement) posted by a user.
 * This class maps directly to the annunci table and supports exclusive 
 * categorization for either car or a spare part.
 */
public class Listing {

    /**
     * Defines the operational lifecycles of a listing within the marketplace.
     */
    public enum ListingStatus {
        /** The listing is public and items are available for purchase. */
        ATTIVO("Attivo"),
        /** The listing has been hidden or deactivated by the creator or admin. */
        DISATTIVATO("Disattivato"),
        /** The listed item has been sold successfully. */
        VENDUTO("Venduto");

        private final String dbValue;

        ListingStatus(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the listing status.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a string text into its matching ListingStatus enum constant.
         * @param text The string status identifier.
         * @return The corresponding {@link ListingStatus} constant.
         * @throws IllegalArgumentException If the text does not match a valid status.
         */
        public static ListingStatus fromString(String text) {
            for (ListingStatus status : ListingStatus.values()) {
                if (status.getDbValue().equalsIgnoreCase(text) || status.name().equalsIgnoreCase(text)) {
                    return status;
                }
            }
            throw new IllegalArgumentException("Invalid listing status: " + text);
        }
    }

    /**
     * Defines whether the listing advertises a car or a spare part.
     */
    public enum ListingType {
        /** The listing is selling a car. */
        AUTO("Auto"),
        /** The listing is selling a spare part. */
        PEZZO("Pezzo");

        private final String dbValue;

        ListingType(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * @return The database string representation of the listing type.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a string text into its matching ListingType enum constant.
         * @param text The string type identifier.
         * @return The corresponding {@link ListingType} constant.
         * @throws IllegalArgumentException If the text does not match a valid type.
         */
        public static ListingType fromString(String text) {
            for (ListingType type : ListingType.values()) {
                if (type.getDbValue().equalsIgnoreCase(text) || type.name().equalsIgnoreCase(text)) {
                    return type;
                }
            }
            throw new IllegalArgumentException("Invalid listing type: " + text);
        }
    }

    private int listingId;
    private LocalDate creationDate;
    private ListingStatus status;
    private BigDecimal price;
    private ListingType listingType;
    private Car car;             // Nullable if listing is for a SparePart
    private SparePart sparePart; // Nullable if listing is for a Car
    private User user;


    /**
     * Complete Object-Oriented Constructor.
     * @param listingId    The unique system identifier generated by the database (idAnnuncio).
     * @param creationDate The date the listing was published (DataInserimento).
     * @param status       The operational state of the listing (Stato).
     * @param price        The monetary valuation set for the item (Prezzo).
     * @param listingType  The classification parameter selector (TipoAnnuncio).
     * @param car          The associated {@link Car} instance, or {@code null} if this is a part listing.
     * @param sparePart    The associated {@link SparePart} instance, or {@code null} if this is a car listing.
     * @param user         The seller {@link User} account instance (IdUtente).
     */
    public Listing(int listingId, LocalDate creationDate, ListingStatus status, BigDecimal price, 
                   ListingType listingType, Car car, SparePart sparePart, User user) {
        this.listingId = listingId;
        this.creationDate = creationDate;
        this.status = status;
        this.price = price;
        this.listingType = listingType;
        this.car = car;
        this.sparePart = sparePart;
        this.user = user;
    }


    public int getListingId() {
        return listingId;
    }


    public LocalDate getCreationDate() {
        return creationDate;
    }


    public ListingStatus getStatus() {
        return status;
    }


    public BigDecimal getPrice() {
        return price;
    }


    public ListingType getListingType() {
        return listingType;
    }


    public Car getCar() {
        return car;
    }


    public SparePart getSparePart() {
        return sparePart;
    }


    public User getUser() {
        return user;
    }
    
    @Override
    public String toString() {
        return "Listing{" +
                "listingId=" + listingId +
                ", creationDate=" + creationDate +
                ", status=" + status +
                ", price=" + price +
                ", listingType=" + listingType +
                ", car=" + (car != null ? car : "null") +
                ", sparePart=" + (sparePart != null ? sparePart : "null") +
                ", user=" + (user != null ? user : "null") +
                '}';
    }

    /**
     * Data Access Object (DAO) providing persistent storage capabilities for {@link Listing} entities.
     */
    public static final class DAO {

        /**
         * Retrieves a paginated list of car listings based on active search criteria.
         *
         * @param connection the active database connection
         * @param filter     the filter criteria and pagination rules
         * @return           a list of matching and fully populated {@link Listing} entities
         * @throws DAOException if a database access error or mapping failure occurs
         */
        public static List<Listing> showCarListings(Connection connection, CarFilter filter) {
            List<Listing> carListings = new ArrayList<>();
            try (
                var statement = DAOUtils.prepare(connection, Queries.SEARCH_CAR_LISTING,filter.getModelId(), filter.getModelId(),
                    filter.getFuelTypeId(), filter.getFuelTypeId(),
                    filter.getTransmissionType(), filter.getTransmissionType(),
                    filter.getExteriorColorId(), filter.getExteriorColorId(),
                    filter.getInteriorColorId(), filter.getInteriorColorId(),
                    filter.getMinPrice(), filter.getMinPrice(),
                    filter.getMaxPrice(), filter.getMaxPrice(),
                    filter.getMinYear(), filter.getMinYear(),
                    filter.getMaxYear(), filter.getMaxYear(),
                    filter.getMinPower(), filter.getMinPower(),
                    filter.getMaxPower(), filter.getMaxPower(),
                    filter.getOffset()
                );
                var resultSet = statement.executeQuery();
            )
            {
                while (resultSet.next()) {
                    Color exteriorColor = new Color(
                        resultSet.getInt("IdColoreEsterno"), 
                        resultSet.getString("NomeColoreEsterno")
                    );

                    Color interiorColor = new Color(
                        resultSet.getInt("IdColoreInterno"), 
                        resultSet.getString("NomeColoreInterno")
                    );

                    Producer producer = new Producer(
                        resultSet.getInt("IdProduttore"),
                        resultSet.getString("NomeMarca"),
                        resultSet.getString("Nazionalita"),
                        resultSet.getInt("AutoVendute")
                    );

                    // Now, pass the Producer instance into your CarModel constructor
                    CarModel carModel = new CarModel(
                        resultSet.getInt("IdModello"),
                        resultSet.getString("NomeModello"),
                        producer
                    );

                    FuelType fuelType = new FuelType(
                        resultSet.getInt("IdAlimentazione"),
                        resultSet.getString("NomeAlimentazione")
                    );

                    // Construct a placeholder User instance for the seller
                    User user = User.DAO.findUser(connection, resultSet.getInt("IdUtente"));
                    
                    
                    // Equipments collection starts empty; can be populated later dynamically
                    List<Accessory> equipments = Accessory.DAO.listAccesory(connection, resultSet.getInt("IdAuto"));

                    //Build the Car domain entity using its loaded constructor
                    Car car = new Car(
                        resultSet.getInt("IdAuto"),
                        resultSet.getString("VIN"),
                        resultSet.getString("Targa"),
                        resultSet.getInt("AnnoPrimaImmatricolazione"),
                        resultSet.getInt("Potenza"),
                        TransmissionType.valueOf(resultSet.getString("TipoCambio").toUpperCase()),
                        Availability.valueOf(resultSet.getString("Disponibilita").toUpperCase()),
                        carModel,
                        fuelType,
                        interiorColor,
                        exteriorColor,
                        user,
                        equipments
                    );

                    //Build the final Listing entity via its OO Constructor
                    Listing listing = new Listing(
                        resultSet.getInt("idAnnuncio"),
                        resultSet.getObject("DataInserimento", java.time.LocalDate.class),
                        ListingStatus.valueOf(resultSet.getString("Stato").toUpperCase()),
                        resultSet.getBigDecimal("Prezzo"),
                        ListingType.AUTO, // Hardcoded since this method specifically processes car listings
                        car,
                        null,            // sparePart is null because this is a car listing
                        user
                    );

                    carListings.add(listing);
                }
                
            } catch (Exception e) {
                throw new DAOException(e);
            }

            return carListings;
        }

        /**
         * Retrieves a paginated list of spare part listings based on active search criteria.
         *
         * @param connection the active database connection
         * @param filter     the filter criteria and pagination rules (SparePartFilter)
         * @return           a list of matching and fully populated {@link Listing} entities
         * @throws DAOException if a database access error or mapping failure occurs
         */
        public static List<Listing> showSparePartListings(Connection connection, SparePartFilter filter) {
            List<Listing> sparePartListings = new ArrayList<>();
            try (
                var statement = DAOUtils.prepare(connection, Queries.SEARCH_SPAREPART_LISTING,
                    filter.getModelId(),  filter.getModelId(),          // Usato per la JOIN di compatibilità
                    filter.getMinPrice(), filter.getMinPrice(),
                    filter.getMaxPrice(), filter.getMaxPrice(),
                    filter.getOffset()
                );
                var resultSet = statement.executeQuery();
            ) 
            {
                while (resultSet.next()) {   
                    // 1. Costruisci l'oggetto Produttore del pezzo
                    Producer producer = new Producer(
                        resultSet.getInt("IdProduttore"),
                        resultSet.getString("NomeMarca"),
                        resultSet.getString("Nazionalita"),
                        resultSet.getInt("AutoVendute")
                    );

                    List<CarModel> compatibility = CarModel.DAO.listCompatibility(connection, resultSet.getInt("IdPezzo"));

                    // 2. Costruisci l'entità di dominio SparePart (Pezzo di Ricambio)
                    SparePart sparePart = new SparePart(
                        resultSet.getInt("IdPezzo"),
                        resultSet.getString("NomePezzo"),
                        resultSet.getInt("QuantitàMagazzino"),
                        resultSet.getString("Tipologia"),
                        resultSet.getInt("PezziVenduti"),
                        producer,
                        compatibility
                    );

                    // 3. Recupera l'utente venditore dell'annuncio
                    User user = User.DAO.findUser(connection, resultSet.getInt("IdUtente"));
                    
                    // 4. (Opzionale) Se la tua entità SparePart tiene traccia dei modelli compatibili:
                    // List<CarModel> compatibleModels = CarModel.DAO.listCompatibleModels(connection, resultSet.getInt("IdPezzo"));

                    // 5. Costruisci l'entità finale Listing (Annuncio) via OO Constructor
                    Listing listing = new Listing(
                        resultSet.getInt("idAnnuncio"),
                        resultSet.getObject("DataInserimento", java.time.LocalDate.class),
                        ListingStatus.valueOf(resultSet.getString("Stato").toUpperCase()),
                        resultSet.getBigDecimal("Prezzo"),
                        ListingType.PEZZO, // Hardcoded: questo metodo elabora solo ricambi
                        null,              // car è null perché questo è un annuncio di un pezzo
                        sparePart,         // Passiamo l'entità del pezzo appena creata
                        user
                    );

                    sparePartListings.add(listing);
                }
                
            } catch (Exception e) {
                throw new DAOException(e);
            }

            return sparePartListings;
        }
    }
}

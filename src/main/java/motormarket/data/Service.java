package motormarket.data;

import java.math.BigDecimal;
import java.sql.Connection;
import java.util.ArrayList;
import java.util.List;

/**
 * Represents a premium Service offered within the marketplace.
 * This class maps directly to the servizi table and categorizes services 
 * based on whether they apply to vehicles or spare parts.
 */
public class Service {

    /**
     * Defines the target category to which the service can be applied.
     */
    public enum ServiceType {
        /** The service is applicable to car listings or vehicles. */
        AUTO("Auto"),
        /** The service is applicable to spare parts listings. */
        PEZZO("Pezzo");

        /** The literal string representation stored within the database column. */
        private final String dbValue;

        ServiceType(String dbValue) {
            this.dbValue = dbValue;
        }

        /**
         * Gets the raw string representation stored in the database.
         * * @return The database string representation of the service type.
         */
        public String getDbValue() {
            return dbValue;
        }

        /**
         * Converts a raw input string into its corresponding ServiceType enum constant.
         * @param text The string name of the service type to convert.
         * @return The matching {@link ServiceType} enum constant.
         * @throws IllegalArgumentException If the provided text does not match any service type.
         */
        public static ServiceType fromString(String text) {
            for (ServiceType type : ServiceType.values()) {
                if (type.getDbValue().equalsIgnoreCase(text) || type.name().equalsIgnoreCase(text)) {
                    return type;
                }
            }
            throw new IllegalArgumentException("Invalid service type: " + text);
        }
    }

    private int serviceId;
    private String name;
    private BigDecimal price;
    private ServiceType serviceType;

    /**
     * Complete constructor containing all database mapped fields.
     * Primarily used by the DAO layer to instantiate the entity from database records.
     * @param serviceId   The unique system identifier generated by the database (IdServizio).
     * @param name        The display name of the service.
     * @param price       The monetary cost of the service.
     * @param serviceType The classification type (AUTO or PEZZO).
     */
    public Service(int serviceId, String name, BigDecimal price, ServiceType serviceType) {
        this.serviceId = serviceId;
        this.name = name;
        this.price = price;
        this.serviceType = serviceType;
    }

    public int getServiceId() {
        return serviceId;
    }

    public String getName() {
        return name;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public ServiceType getServiceType() {
        return serviceType;
    }

    @Override
    public String toString() {
        return "Service{" +
                "serviceId=" + serviceId +
                ", name='" + name + '\'' +
                ", price=" + price +
                ", serviceType=" + serviceType +
                '}';
    }

    /**
     * Data Access Object (DAO) providing persistent storage capabilities for {@link Service} entities.
     * Handles database CRUD interactions related to services.
     */
    public static final class DAO {

       /**
         * Inserts a new extra service provided by the platform into the database.
         * @param connection the active database connection
         * @param name the name of the service ("NomeServizio")
         * @param serviceType the category or type of the service ("TipoServizio")
         * @param price the cost of the extra service ("Prezzo")
         * @return true if the service was successfully added, false otherwise
         * @throws DAOException if a database access error occurs
         */
        public static boolean addExtraService(Connection connection, String name, String serviceType, double price) throws DAOException {
            try (var statement = DAOUtils.prepare(connection, Queries.INSERT_EXTRA_SERVICE, name, serviceType, price)) {
                
                int rowsInserted = statement.executeUpdate();
                return rowsInserted > 0;
                
            } catch (Exception e) {
                throw new DAOException(e);
            }
        }

        /**
         * Finds all services associeted to an {@link order}
         * 
         * @param connection the active database connection
         * @param orderId the unique system identifier of the order
         * @return a list of all services in an order
         * @throws DAOException if a database access error occurs or parsing fails
         */
        public static List<Service> listService(Connection connection, int orderId){
            List<Service> services = new ArrayList<>();
            try (
                var statement = DAOUtils.prepare(connection, Queries.GET_ADDITION, orderId);
                var resultSet = statement.executeQuery();
            ) {
                while (resultSet.next()) {
                    var serviceId = resultSet.getInt("IdServizio");
                    var name = resultSet.getString("Nome");
                    var price = resultSet.getBigDecimal("Prezzo");
                    var type = resultSet.getString("TipoServizio");
                    services.add(new Service(serviceId, name, price, ServiceType.fromString(type) ));
                }
                
            } catch (Exception e) {
                throw new DAOException(e);
            }
            
            return services;
        }

    }
}
